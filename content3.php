            <h2>Pemko Siantar Dorong Pariwisata Lokal dan UMKM</h2> 
            <img src="images/content3.png" alt="Pariwisata dan UMKM Siantar" class="article-image">
            
           <p>Pemerintah Kota Pematangsiantar terus berupaya mendorong sektor pariwisata lokal dan Usaha Mikro, Kecil, dan Menengah (UMKM) sebagai pilar ekonomi. Berbagai program strategis diluncurkan untuk meningkatkan daya tarik wisata kota dan kualitas produk UMKM lokal agar mampu bersaing.</p>

           <p>Walikota Pematangsiantar menyatakan bahwa sinergi antara sektor pariwisata dan UMKM sangat penting. "Ketika pariwisata tumbuh, permintaan akan produk lokal seperti kuliner, kerajinan tangan, dan jasa lainnya juga akan meningkat. Ini adalah kesempatan emas bagi pelaku UMKM kita untuk naik kelas," ujarnya saat membuka acara festival budaya lokal baru-baru ini.</p>
            
           <p>Selain promosi, Pemko juga fokus pada peningkatan infrastruktur di berbagai destinasi wisata andalan serta memberikan pelatihan digital marketing bagi para pelaku UMKM. Diharapkan dengan langkah ini, Pematangsiantar dapat menjadi salah satu tujuan wisata favorit di Sumatera Utara yang berbasis pada kekuatan ekonomi kreatif lokal dan mandiri.</p>
