            <h2>Pemko Medan Genjot Perbaikan Drainase Atasi Banjir</h2>
            
            <img src="images/content1.png" alt="Belajar Web" class="article-image">
            
            <p>Pemerintah Kota Medan terus menggenjot perbaikan infrastruktur, khususnya drainase dan jalan, di berbagai wilayah. Wali Kota Bobby Nasution menekankan pentingnya penanganan banjir yang komprehensif dan meminta seluruh jajaran terkait untuk bekerja cepat menuntaskan proyek-proyek yang sedang berjalan. Fokus utama saat ini adalah normalisasi sungai dan perbaikan total sistem saluran air kota.</p>

        <p>Perbaikan drainase dilakukan secara besar-besaran untuk mengurangi genangan air saat curah hujan tinggi, terutama di kawasan-kawasan yang menjadi langganan banjir. Proyek ini meliputi revitalisasi saluran air primer dan sekunder, serta peningkatan kapasitas pompa air di beberapa titik strategis. Salah satu proyek vital adalah pembangunan tanggul air untuk melindungi area padat penduduk dari luapan sungai saat musim hujan puncak.</p>
      
        <p>Proyek ini diawasi ketat oleh dinas terkait, memastikan setiap pengerjaan sesuai dengan standar teknis dan target waktu yang ditetapkan. Pihak Pemko juga mengajak partisipasi warga untuk tidak membuang sampah ke saluran air guna menjaga keefektifan sistem drainase. Warga dihimbau untuk aktif melaporkan titik-titik genangan yang belum tertangani melalui kanal pengaduan resmi pemerintah kota. Diharapkan program ini dapat memberikan dampak signifikan pada kualitas hidup masyarakat kota Medan dalam jangka panjang.</p>
